#!/bin/bash

# ==============================================================================
# Настройки путей и параметров
# ==============================================================================
# Определяем абсолютный путь к директории, где лежит этот скрипт (корень проекта)
SCRIPT_DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" && pwd )"
BUILD_DIR="$SCRIPT_DIR/build"
EXECUTABLE="$BUILD_DIR/Lab_02"

# Параметры задачи
NX=200
NY=200
NZ=200
TOTAL_THREADS=12 # Фиксируем общее число потоков для честного сравнения конфигураций

# ==============================================================================
# Приветствие и проверки
# ==============================================================================
echo "========================================================"
echo "  Гибридный бенчмарк (MPI + OpenMP)"
echo "  Размер сетки: ${NX} x ${NY} x ${NZ}"
echo "  Фиксированное общее число потоков: $TOTAL_THREADS"
echo "========================================================"

# Проверка наличия исполняемого файла
if [ ! -f "$EXECUTABLE" ]; then
    echo "❌ Ошибка: Исполняемый файл не найден по пути: $EXECUTABLE"
    echo "💡 Сначала соберите проект, выполнив:"
    echo "   cmake --build $BUILD_DIR"
    exit 1
fi

echo "Запуск тестов (каждая конфигурация выполняется 3 раза, берется минимальное время)..."
echo "--------------------------------------------------------"
printf "%-15s | %-15s | %-10s\n" "Конфигурация" "Мин. время (сек)" "Статус"
echo "--------------------------------------------------------"

# Варианты разбиения для 12 потоков: 12x1, 6x2, 4x3, 3x4, 2x6, 1x12
MPI_PROCS=(12 6 4 3 2 1)

for mpi in "${MPI_PROCS[@]}"; do
    # Вычисляем количество OpenMP потоков
    omp=$((TOTAL_THREADS / mpi))

    # Запускаем 3 раза и берем минимальное время (grep и awk извлекают время MPI TIME)
    min_time=9999.9
    for i in {1..3}; do
        # Запускаем программу и сохраняем весь вывод (stdout + stderr) в переменную
        output=$(OMP_NUM_THREADS=$omp mpirun --oversubscribe -np $mpi "$EXECUTABLE" $NX $NY $NZ 2>&1)

        # Извлекаем время из строки: "Общее время счета (MPI TIME): 0.3060 sec."
        # awk '{print $6}' берет 6-е слово, которое является числом
        time=$(echo "$output" | grep "MPI TIME" | awk '{print $6}')

        # Сравниваем с помощью awk
        is_less=$(awk -v t="$time" -v m="$min_time" 'BEGIN {print (t < m) ? 1 : 0}')
        if [ "$is_less" -eq 1 ]; then
            min_time=$time
        fi
    done

    printf "%-5d x %-5d | %-15.5f | OK\n" "$mpi" "$omp" "$min_time"
done

echo "========================================================"
echo "✅ Бенчмарк успешно завершен!"
echo "💡 Совет: Для отчета используйте конфигурацию с минимальным временем."