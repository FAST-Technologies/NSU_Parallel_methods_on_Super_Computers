/**
 * @brief Точное аналитическое решение для контроля и граничных условий.
 * @details Используется для задания граничных условий 1-го рода (Дирихле)
 *          и для проверки точности полученного численного решения.
 * @param x Координата X.
 * @param y Координата Y.
 * @param z Координата Z.
 * @return Значение функции φ(x,y,z) = x² + y² + z².
 */
double exact_solution(double x, double y, double z);

/**
 * @brief Функция правой части уравнения Пуассона.
 * @details Уравнение: p = Δφ - a·φ = 6 - a*(x² + y² + z²). Для φ = x²+y²+z² лапласиан Δφ = 6.
 *          Δφ - Лапласиан, равный d²phi/dx² + d²phi/dy² + d²phi/dz².
 * @param x Координата X.
 * @param y Координата Y.
 * @param z Координата Z.
 * @return Значение правой части ρ(x,y,z) = 6 - a·(x²+y²+z²).
 */
double rhs_function(double x, double y, double z);

