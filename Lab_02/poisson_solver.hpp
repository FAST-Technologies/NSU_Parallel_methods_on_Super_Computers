#ifdef USE_MPE
#include <mpe.h>

/**
 * @brief Структура, хранящая идентификаторы событий для настраиваемого профилирования MPE.
 * @details Используется для маркировки временных интервалов различных фаз итерационного
 *          процесса (обмен границами, вычисления, ожидание) с целью последующей
 *          визуализации в Jumpshot. Избегает использования глобальных переменных.
 */
struct MPEEvents {
    int begin_halo = 0;     ///< Идентификатор начала фазы упаковки и запуска асинхронных обменов (Halo Exchange).
    int end_halo = 0;       ///< Идентификатор конца фазы упаковки и запуска асинхронных обменов.
    int begin_comp_int = 0; ///< Идентификатор начала фазы вычисления внутренних точек (перекрытие с коммуникациями).
    int end_comp_int = 0;   ///< Идентификатор конца фазы вычисления внутренних точек.
    int begin_wait = 0;     ///< Идентификатор начала фазы ожидания завершения асинхронных обменов (MPI_Waitall).
    int end_wait = 0;       ///< Идентификатор конца фазы ожидания завершения асинхронных обменов.
    int begin_comp_bnd = 0; ///< Идентификатор начала фазы распаковки ghost-слоев и вычисления граничных точек.
    int end_comp_bnd = 0;   ///< Идентификатор конца фазы распаковки ghost-слоев и вычисления граничных точек.
};
#endif

/**
 * @brief Структура, хранящая параметры декомпозиции и сетки для текущего MPI-процесса.
 * @details Содержит все необходимые данные о локальной подобласти, включая размеры,
 *          координаты в топологии, информацию о соседях и параметры сетки.
 */
struct DomainInfo {
    int local_nx; ///< Локальный размер сетки по X (без ghost-слоев).
    int local_ny; ///< Локальный размер сетки по Y (без ghost-слоев).
    int local_nz; ///< Локальный размер сетки по Z (без ghost-слоев).
    int coords[2]; ///< Координаты процесса в 2D декартовой топологии.
    int left; ///< Ранг соседа слева (по оси X).
    int right; ///< Ранг соседа справа (по оси X).
    int top; ///< Ранг соседа сверху (по оси Y).
    int bottom; ///< Ранг соседа снизу (по оси Y).
    double hx; ///< Шаг сетки по оси X.
    double hy; ///< Шаг сетки по оси Y.
    double hz; ///< Шаг сетки по оси Z.
    double denom; ///< Знаменатель в формуле метода Якоби.
    MPI_Comm cart_comm; ///< Коммуникатор декартовой топологии.
};

// ============================================================================
// Структура для сбора статистики профилирования
// ============================================================================

/**
 * @brief Структура для сбора и агрегации статистики профилирования итерационного процесса.
 * @details Используется для накопления временных метрик на различных этапах выполнения
 *          цикла метода Якоби с целью последующего анализа эффективности перекрытия вычислений и коммуникаций (Overlap Efficiency).
 *          Статистика собирается локально в каждом MPI-процессе и впоследствие агрегируется
 *          с помощью коллективных операций MPI_Reduce.
 */
struct ProfilingStats {
    double total_loop_time = 0.0;       ///< Общее время выполнения итерационного цикла, накопленное локально (включая вычисления, обмены и синхронизацию, в секундах).
    double total_compute_time = 0.0;    ///< Суммарное время вычисления внутренних точек (перекрытие с коммуникациями), накопленное локально (в секундах).
    double total_wait_time = 0.0;       ///< Суммарное время ожидания завершения асинхронных MPI-обменов (MPI_Waitall), накопленное локально (в секундах).
    int iterations = 0;                 ///< Общее количество выполненных итераций метода Якоби до достижения критерия сходимости.
};

