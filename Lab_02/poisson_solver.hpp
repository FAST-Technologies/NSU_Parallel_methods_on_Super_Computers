/**
 * @file poisson_solver.hpp
 * @brief Заголовочный файл для параллельного решателя уравнения Пуассона методом Якоби.
 * @details Содержит структуру данных, константы и прототипы функций для решения
 *          трехмерного уравнения Пуассона с использованием гибридной модели MPI + OpenMP.
 *          Реализована двумерная декомпозиция области, виртуальная топология,
 *          неблокирующие обмены (halo exchange) и перекрытие вычислений с коммуникациями.
 * @author F.A.S.T. DEVELOPMENT Refactored for educational purposes.
 * @version 1.0.
 */

#ifndef POISSON_SOLVER_HPP
#define POISSON_SOLVER_HPP

#include <mpi.h>
#include <vector>

// ============================================================================
// Глобальные параметры задачи
// ============================================================================

/** @brief Начальная координата области по оси X. */
constexpr double X0 = -1.0;

/** @brief Начальная координата области по оси Y. */
constexpr double Y0 = -1.0;

/** @brief Начальная координата области по оси Z. */
constexpr double Z0 = -1.0;

/** @brief Размер области по оси X. */
constexpr double DX = 2.0;

/** @brief Размер области по оси Y. */
constexpr double DY = 2.0;

/** @brief Размер области по оси Z. */
constexpr double DZ = 2.0;

/** @brief Параметр уравнения Пуассона (a). */
constexpr double A_PARAM = 1e5;

/** @brief Порог сходимости итерационного процесса (ε). */
constexpr double EPSILON = 1e-8;

/** @brief Максимальное количество итераций. */
constexpr int MAX_ITER = 10000;

// ============================================================================
// Структуры данных
// ============================================================================

/**
 * @brief Структура, хранящая параметры декомпозиции и сетки для текущего MPI-процесса.
 * @details Содержит все необходимые данные о локальной подобласти, включая размеры,
 *          координаты в топологии, информацию о соседях и параметры сетки.
 */
struct DomainInfo {
    int local_nx; ///< Локальный размер сетки по X (без ghost-слоев).
    int local_ny; ///< Локальный размер сетки по Y (без ghost-слоев).
    int local_nz; ///< Локальный размер сетки по Z (без ghost-слоев).
    int coords[2]; ///< Координаты процесса в 2D декартовой топологии.
    int left; ///< Ранг соседа слева (по оси X).
    int right; ///< Ранг соседа справа (по оси X).
    int top; ///< Ранг соседа сверху (по оси Y).
    int bottom; ///< Ранг соседа снизу (по оси Y).
    double hx; ///< Шаг сетки по оси X.
    double hy; ///< Шаг сетки по оси Y.
    double hz; ///< Шаг сетки по оси Z.
    double denom; ///< Знаменатель в формуле метода Якоби.
    MPI_Comm cart_comm; ///< Коммуникатор декартовой топологии.
};

// ============================================================================
// Математические функции
// ============================================================================

/**
 * @brief Точное аналитическое решение для контроля и граничных условий.
 * @details Используется для задания граничных условий 1-го рода (Дирихле)
 *          и для проверки точности полученного численного решения.
 * @param x Координата X.
 * @param y Координата Y.
 * @param z Координата Z.
 * @return Значение функции φ(x,y,z) = x² + y² + z².
 */
double exact_solution(double x, double y, double z);

/**
 * @brief Функция правой части уравнения Пуассона.
 * @details Уравнение: p = Δφ - a·φ = 6 - a*(x² + y² + z²). Для φ = x²+y²+z² лапласиан Δφ = 6.
 *          Δφ - Лапласиан, равный d²phi/dx² + d²phi/dy² + d²phi/dz².
 * @param x Координата X.
 * @param y Координата Y.
 * @param z Координата Z.
 * @return Значение правой части ρ(x,y,z) = 6 - a·(x²+y²+z²).
 */
double rhs_function(double x, double y, double z);

// ============================================================================
// Функции инициализации и итерационного процесса
// ============================================================================

/**
 * @brief Безопасное получение целочисленного аргумента из командной строки.
 * @param argc Количество аргументов.
 * @param argv Массив аргументов.
 * @param arg_index Индекс требуемого аргумента (начиная с 1).
 * @param default_value Значение по умолчанию, если аргумент отсутствует или некорректен.
 * @return Преобразованное целое число или default_value.
 */
int get_int_arg(int argc, char** argv, int arg_index, int default_value);

/**
 * @brief Инициализация сетки: задание граничных условий и начального приближения.
 * @details Заполняет массив phi начальными значениями. На границах области
 *          задаются значения точного решения (граничные условия Дирихле),
 *          во внутренней области - нулевое начальное приближение.
 * @param phi Ссылка на вектор значений функции (включая ghost-слои).
 * @param info Структура с параметрами домена.
 * @param Nx Глобальный размер сетки по X.
 * @param Ny Глобальный размер сетки по Y.
 * @param Nz Глобальный размер сетки по Z.
 */
void initialize_grid(std::vector<double>& phi, const DomainInfo& info,
                     int Nx, int Ny, int Nz);

/**
 * @brief Выполнение одного шага метода Якоби с перекрытием вычислений и обменов.
 * @details Реализует один итерационный шаг метода Якоби с использованием
 *          неблокирующих MPI-обменов для перекрытия коммуникаций и вычислений.
 *          Алгоритм:
 *          1. Упаковка данных и запуск асинхронных обменов (Non-blocking).
 *          2. Вычисление внутренних точек (перекрытие с коммуникациями).
 *          3. Ожидание завершения всех обменов.
 *          4. Распаковка полученных данных в ghost-слои.
 *          5. Вычисление граничных точек локальной подобласти.
 * @param phi Текущее приближение решения (включая ghost-слои).
 * @param phi_new Вектор для записи нового приближения.
 * @param info Структура с параметрами домена.
 * @param Nx Глобальный размер сетки по X.
 * @param Ny Глобальный размер сетки по Y.
 * @param Nz Глобальный размер сетки по Z.
 * @param max_diff Ссылка на переменную для записи локальной максимальной невязки.
 */
void jacobi_step(std::vector<double>& phi, std::vector<double>& phi_new,
                 const DomainInfo& info, int Nx, int Ny, int Nz, double& max_diff);

#endif // POISSON_SOLVER_HPP