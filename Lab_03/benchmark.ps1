$ErrorActionPreference = "Stop"
$RESULTS_DIR = Join-Path $PSScriptRoot "results"
$BUILDS = @(
    @{
        Name = "float"
        Directory = "build-float"
    },
    @{
        Name = "double"
        Directory = "build-double"
    }
)

Write-Host "========================================================"
Write-Host "  CUDA Matrix Multiplication Benchmark"
Write-Host "  Precision: float + double"
Write-Host "  Matrix sizes are taken from config.hpp (MATRIX_SIZES)"
Write-Host "  Repeats and warmup are handled by the C++ program"
Write-Host "========================================================"

New-Item -ItemType Directory -Force -Path $RESULTS_DIR | Out-Null

foreach ($BUILD in $BUILDS) {
    $BUILD_DIR = Join-Path $PSScriptRoot $BUILD.Directory
    $EXECUTABLE = Join-Path $BUILD_DIR "Lab_03.exe"

    Write-Host ""
    Write-Host "--------------------------------------------------------"
    Write-Host "Running $($BUILD.Name) benchmark"
    Write-Host "Executable: $EXECUTABLE"
    Write-Host "--------------------------------------------------------"

    if (-not (Test-Path $EXECUTABLE)) {
        throw "Executable not found: $EXECUTABLE. Build the configuration first."
    }

    # Remove only previous CSV files generated by this build.
    Get-ChildItem -Path $BUILD_DIR -Filter "*.csv" -File |
        Remove-Item -Force

    Push-Location $BUILD_DIR
    try {
        & ".\Lab_03.exe"

        if ($LASTEXITCODE -ne 0) {
            throw "Benchmark ($($BUILD.Name)) failed with exit code $LASTEXITCODE."
        }
    }
    finally {
        Pop-Location
    }

    # Collect all non-empty CSV files generated by the current run.
    $CSV_FILES = @(
        Get-ChildItem -Path $BUILD_DIR -Filter "*.csv" -File |
            Where-Object { $_.Length -gt 0 }
    )

    if ($CSV_FILES.Count -eq 0) {
        throw "No non-empty CSV files were generated for $($BUILD.Name)."
    }

    $PRECISION_RESULTS = Join-Path $RESULTS_DIR $BUILD.Name
    New-Item -ItemType Directory -Force -Path $PRECISION_RESULTS | Out-Null

    foreach ($CSV_SOURCE in $CSV_FILES) {
        $CSV_DESTINATION = Join-Path $PRECISION_RESULTS $CSV_SOURCE.Name

        Copy-Item -Force $CSV_SOURCE.FullName $CSV_DESTINATION

        Write-Host "Saved: $CSV_DESTINATION" -ForegroundColor Green
    }
}

Write-Host ""
Write-Host "========================================================"
Write-Host "All benchmarks completed successfully."
Write-Host "Results directory: $RESULTS_DIR"
Write-Host "========================================================"
