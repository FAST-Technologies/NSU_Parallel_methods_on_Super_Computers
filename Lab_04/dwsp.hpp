/**
 * @file dwsp.hpp
 * @brief Объявления компонентов протокола динамического распределения задач DWSP.
 *
 * @details
 * Проект DWSP (Dynamic Work Stealing Protocol) реализует гибридную
 * параллельную обработку задач с использованием MPI и POSIX Threads.
 *
 * Каждый MPI-процесс содержит:
 * - несколько Worker-потоков для выполнения задач;
 * - один Fetcher-поток для получения задач от других процессов;
 * - один Responder-поток для обработки входящих запросов.
 *
 * Для синхронизации потоков используются мьютекс и две условные переменные.
 *
 * @author F.A.S.T. DEVELOPMENT aka Ямщиков Владимир, группа 26162.
 * @date 15.11.2026.
 * @version 1.0
 */

/**
 * @mainpage DWSP — Dynamic Work Stealing Protocol
 *
 * @section architecture Архитектура программы
 *
 * Каждый MPI-процесс содержит:
 *
 * - 4 Worker;
 * - 1 Fetcher;
 * - 1 Responder.
 *
 * @section synchronization Синхронизация
 *
 * Для взаимодействия потоков используются:
 *
 * - mutex — защита общей очереди задач;
 * - c_jobAdded — уведомление Worker о новой работе;
 * - c_needToFetch — уведомление Fetcher об опустошении очереди.
 *
 * @section mpi MPI-взаимодействие
 *
 * MPI-процессы обмениваются задачами через Fetcher и Responder.
 * Процесс rank 0 дополнительно выполняет роль координатора.
 *
 * @section termination Завершение
 *
 * Координатор ожидает выполнения всех задач и получения
 * уведомлений IDLE от всех MPI-процессов.
 * После этого он рассылает команду TAG_TERMINATE.
 */
#ifndef LAB_04_DWSP_H
#define LAB_04_DWSP_H

#include <mpi.h>
#include <pthread.h>

#include <queue>
#include <atomic>

// ============================================================
// DWSP 1.0
// Dynamic Work Stealing Protocol
// MPI + POSIX Threads
// ============================================================

// ============================================================
// Настройки протокола
// ============================================================
/**
 * @brief Максимальный целевой размер запрашиваемого пакета локальной очереди задач.
 *
 * Fetcher запрашивает у других MPI-процессов недостающие задачи,
 * если локальная очередь становится пустой.
 *
 * Значение используется для определения размера запрашиваемого
 * пакета задач.
 */
constexpr int HIGH_WATERMARK = 6;

// ============================================================
// MPI message tags
// ============================================================

/**
 * @brief Теги MPI-сообщений, используемые протоколом DWSP.
 *
 * Теги позволяют Responder определять назначение входящего
 * MPI-сообщения.
 */
enum MessageTag {
    /** Запрос задач от другого MPI-процесса. */
    TAG_REQUEST = 100,

    /** Ответ с количеством передаваемых задач. */
    TAG_REPLY_COUNT = 101,

    /** Ответ с данными передаваемых задач. */
    TAG_REPLY_DATA = 102,

    /** Уведомление о завершении задачи. */
    TAG_JOB_DONE = 103,

    /** Уведомление Fetcher о прекращении поиска задач. */
    TAG_FETCHER_IDLE = 104,

    /** Команда завершения работы MPI-процесса. */
    TAG_TERMINATE = 105
};

// ============================================================
// Структура задачи
// ============================================================

/**
 * @struct Job
 * @brief Представляет отдельную вычислительную задачу.
 *
 * @details
 * Каждая задача имеет уникальный идентификатор и длительность
 * имитации вычислений.
 *
 * Объекты Job хранятся в локальной очереди MPI-процесса
 * и могут передаваться между процессами.
 */
struct Job {
    /** Уникальный идентификатор задачи. */
    int id;

    /** Длительность обработки задачи в миллисекундах. */
    int durationMs;

    /** @brief Создаёт пустую задачу с идентификатором -1. */
    Job();

    /**
     * @brief Создаёт задачу с заданными параметрами.
     *
     * @param jobId Идентификатор задачи.
     * @param duration Длительность обработки в миллисекундах.
     */
    Job(int jobId, int duration);

    /**
     * @brief Выполняет задачу.
     *
     * @details
     * В текущей версии вычислительная нагрузка моделируется
     * ожиданием заданного количества миллисекунд.
     */
    void process() const;
};

// ============================================================
// Общие данные MPI-процесса
// ============================================================

/**
 * @brief Очередь задач текущего MPI-процесса.
 *
 * Доступ к очереди осуществляется только под защитой mutex.
 */
extern std::queue<Job> jobQueue;

/**
 * @brief Дублированный MPI-коммуникатор для ответов на запросы.
 *
 * Используется Fetcher и Responder для обмена количеством
 * передаваемых задач и их содержимым.
 */
extern MPI_Comm replyComm;

/**
 * @brief Мьютекс защиты общих данных процесса.
 *
 * Защищает очередь jobQueue и состояние завершения потоков.
 */
extern pthread_mutex_t mutex;

/**
 * @brief Условная переменная для уведомления Worker о новой работе.
 *
 * Worker ожидает эту переменную, когда локальная очередь пуста.
 * Fetcher уведомляет ожидающие Worker после добавления задач.
 */
extern pthread_cond_t c_jobAdded;

/**
 * @brief Условная переменная для пробуждения Fetcher.
 *
 * Worker и Responder сигнализируют Fetcher, когда локальная
 * очередь становится пустой.
 */
extern pthread_cond_t c_needToFetch;

/**
 * @brief Флаг запроса завершения потоков текущего процесса.
 *
 * Доступ к переменной осуществляется под защитой mutex.
 */
extern bool shutdownRequested;

/** @brief Номер текущего MPI-процесса. */
extern int rank;

/** @brief Общее количество MPI-процессов. */
extern int size;

/** @brief Общее количество задач в эксперименте. */
extern int totalJobs;

/**
 * @brief Счётчик выполненных задач текущим MPI-процессом.
 *
 * Атомарный тип обеспечивает безопасное обновление счётчика
 * несколькими Worker-потоками.
 */
extern std::atomic<int> jobsCompleted;

/**
 * @brief Счётчик задач, переданных другим MPI-процессам.
 */
extern std::atomic<int> jobsSent;

/**
 * @brief Счётчик задач, полученных от других MPI-процессов.
 */
extern std::atomic<int> jobsReceived;

// ============================================================
// Объявления функций
// ============================================================

/**
 * @brief Инициализирует локальную очередь задач.
 *
 * @param baseMs Базовая длительность обработки задачи.
 *
 * @details
 * Каждая задача назначается ровно одному MPI-процессу
 * по правилу id % size == rank.
 */
void initializeJobs(int baseMs);

/**
 * @brief Запрашивает завершение потоков текущего процесса.
 *
 * @details
 * Устанавливает shutdownRequested и пробуждает все потоки,
 * ожидающие условные переменные.
 */
void requestShutdown();

/**
 * @brief Реализация рабочего потока потоком Worker из локальной очереди.
 *
 * @param arg Неиспользуемый аргумент потока.
 * @return nullptr после завершения потока.
 *
 * @details
 * Worker ожидает появления задач в локальной очереди,
 * извлекает задачу под защитой mutex, выполняет её
 * вне критической секции и отправляет координатору
 * MPI-сообщение о завершении.
 *
 * После выполнения отправляет координатору сообщение
 * TAG_JOB_DONE с идентификатором задачи.
 *
 */
void* worker(void* arg);

/**
 * @brief Реализация потока получения задач Fetcher.
 *
 * @param arg Неиспользуемый аргумент потока.
 * @return nullptr после завершения поиска задач.
 *
 * @details
 * Fetcher ожидает сигнала c_needToFetch, пока локальная
 * очередь содержит задачи. Поиск начинается при опустошении очереди.
 *
 * При опустошении очереди последовательно опрашивает
 * остальные MPI-процессы. Полученные задачи добавляются
 * в локальную очередь, после чего пробуждаются Worker.
 *
 * Если ни один процесс не предоставил задачи, Fetcher
 * сообщает координатору TAG_FETCHER_IDLE и завершает работу.
 */
void* fetcher(void* arg);

/**
 * @brief Реализация потока обработки входящих MPI-запросов Responder.
 *
 * @param arg Неиспользуемый аргумент потока.
 * @return nullptr после завершения потока.
 *
 * @details
 * Responder обрабатывает запросы на передачу задач,
 * сообщения о завершении задач и уведомления Fetcher.
 *
 * При TAG_REQUEST извлекает часть задач из локальной очереди
 * и отправляет их запрашивающему процессу.
 *
 * При TAG_JOB_DONE на процессе rank 0 обновляет информацию
 * о выполненных задачах и проверяет отсутствие повторного
 * завершения одной и той же задачи.
 *
 * При получении TAG_FETCHER_IDLE обновляет счётчик
 * процессов, завершивших поиск дополнительной работы.
 *
 * Если все задачи выполнены и все Fetcher сообщили IDLE,
 * координатор рассылает TAG_TERMINATE.
 */
void* responder(void* arg);

#endif //LAB_04_DWSP_H
